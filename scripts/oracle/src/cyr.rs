//! Cyrius source emission for the generated modules (port plan §6 step 6). Adapted from
//! impetus's `scripts/oracle/src/cyr.rs` (itself kimiya's and tanmatra's).
//!
//! Rules the output must keep (probed on 6.7.18; `docs/development/port-probes/p6_misc.cyr`):
//! - **Hex is never used in a `const`**, where it is an integer and `CONST * x` then does
//!   integer arithmetic. An f64 constant is a positional decimal: the lexer has no exponent
//!   form, and it rounds a decimal literal correctly, so the shortest round-trip digits give
//!   back the oracle's bits.
//! - **Every global gets the `BJ_` prefix.** A bundle is concatenated into its consumers, so
//!   names share one namespace.

use std::fmt::Write as _;

/// `x` as a Cyrius f64 literal: Rust's shortest round-trip digits in positional form (Display
/// never writes an exponent), with a `.0` added to an integral value so that the lexer reads a
/// float, not an integer. The caller has checked that `x` is finite.
pub fn f64_literal(x: f64) -> String {
    let text = format!("{x}");
    if text.contains('.') {
        text
    } else {
        format!("{text}.0")
    }
}

/// The `///` doc block directly above the first line of `src` that starts with `item` (after
/// leading whitespace; attributes in between are skipped), as `# ` comment lines. Only
/// comments are read from the Rust source; values always come from the oracle's API.
pub fn doc_comment(src: &str, item: &str) -> Result<String, String> {
    let lines: Vec<&str> = src.lines().collect();
    let at = lines
        .iter()
        .position(|l| l.trim_start().starts_with(item))
        .ok_or_else(|| format!("no `{item}` in the Rust source"))?;
    let mut docs = Vec::new();
    let mut k = at;
    while k > 0 {
        k -= 1;
        let l = lines[k].trim_start();
        if l.starts_with("#[") {
            continue;
        }
        match l.strip_prefix("///") {
            Some(rest) => docs.push(rest.strip_prefix(' ').unwrap_or(rest).to_string()),
            None => break,
        }
    }
    docs.reverse();
    let mut out = String::new();
    for d in docs {
        let _ = writeln!(out, "{}", comment_line(d.trim_end()));
    }
    Ok(out)
}

/// `line` as a `#` comment, with no trailing space when it is empty (lint-clean).
pub fn comment_line(line: &str) -> String {
    if line.is_empty() {
        "#".to_string()
    } else {
        format!("# {line}")
    }
}

/// The generated-file header: title, provenance, regenerate command, then each note as a
/// comment paragraph.
pub fn header(title: &str, provenance: &str, notes: &[&str]) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "# bijli — {title}");
    out.push_str("#\n");
    let _ = writeln!(
        out,
        "# GENERATED by scripts/oracle from {provenance}. Do not edit."
    );
    out.push_str(
        "# Regenerate: cargo run --release --locked --manifest-path scripts/oracle/Cargo.toml\n",
    );
    for n in notes {
        out.push_str("#\n");
        for line in n.lines() {
            let _ = writeln!(out, "{}", comment_line(line));
        }
    }
    out.push('\n');
    out
}
